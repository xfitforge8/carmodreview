def _diagram_figure(name, code, rel, cap):
    """Shared markup for an inline diagram, with intrinsic size reserved."""
    alt = f'{DIAGRAM_ALT.get(code, "Diagram")}: {cap}'
    w, h = DIAGRAM_SIZE.get(name, (680, 300))
    return (
        f'\n  <figure class="fig fig--diagram">\n'
        f'    <img src="{rel}img/diagrams/{name}.svg" alt="{html.escape(alt)}" loading="lazy" '
        f'width="{w}" height="{h}" decoding="async">\n'
        f'    <figcaption><span class="fig-kicker">{_label(code)}</span> {html.escape(cap)}</figcaption>\n'
        f'  </figure>\n'
    )


def diagram_html(name, code, rel):
    """One labelled diagram figure. Source SVG lives at docs/img/diagrams/."""
    cap = DIAGRAM_CAPTIONS.get(name, {}).get(code) or DIAGRAM_CAPTIONS.get(name, {}).get('en', '')
    return _diagram_figure(name, code, rel, cap)


def find_photos(photo_root, slug):
    """Real photos the owner has added for this slug, in filename order."""
    d = os.path.join(photo_root, slug)
    if not os.path.isdir(d):
        return []
    files = [f for f in sorted(os.listdir(d)) if f.lower().endswith(IMG_EXT)]
    return [os.path.join(d, f) for f in files]


def photo_html(paths, src_dir, slug, code, rel):
    """Photo figures for images that actually exist on disk.

    Captions come from an optional sidecar <name>.txt next to the image; with no
    sidecar the caption is omitted rather than invented.
    """
    out = []
    for p in paths:
        name = os.path.basename(p)
        cap_path = os.path.splitext(p)[0] + '.txt'
        cap = ''
        if os.path.exists(cap_path):
            cap = open(cap_path, encoding='utf-8').read().strip()
        alt = cap or name
        fig_cap = (f'\n    <figcaption>{html.escape(cap)}</figcaption>' if cap else '')
        out.append(
            f'\n  <figure class="fig fig--photo">\n'
            f'    <img src="{rel}img/photos/{slug}/{name}" alt="{html.escape(alt)}" '
            f'loading="lazy" decoding="async">'
            f'{fig_cap}\n'
            f'  </figure>\n'
        )
    return ''.join(out)


def _home_figure(name, code, rel):
    """Homepage variant of a diagram, using the homepage caption."""
    cap = HOME_CAPTIONS.get(name, {}).get(code) or HOME_CAPTIONS.get(name, {}).get('en', '')
    return _diagram_figure(name, code, rel, cap)


def inject_home_figures(body_html, code, rel, photo_paths):
    """Spread homepage diagrams between its sections.

    The homepage dek and links form the opening block, so the first figure lands
    just before the first section heading, the rest one per following heading.
    Any real photos the owner supplies for the homepage follow the diagrams.
    """
    figs = [_home_figure(n, code, rel) for n in HOME_DIAGRAMS]
    if code == 'en' and photo_paths:
        figs.append(photo_html(photo_paths, None, 'home', code, rel))

    if not figs:
        return body_html

    parts = re.split(r'(?=<h[23][\s>])', body_html)
    if len(parts) < 2:
        return body_html + ''.join(figs)

    out = [parts[0]]
    queue = list(figs)
    for part in parts[1:]:
        if queue:
            out.append(queue.pop(0))
        out.append(part)
    out.extend(queue)
    return ''.join(out)


def inject_figures(body_html, slug, code, rel, photo_paths):
    """Place figures through the article body.

    Guides use <h3> for sections, so split on either h2 or h3. The first figure
    lands just before the first section heading (i.e. right after the opening
    prose), and the rest are distributed one per following section heading. That
    keeps a figure near the top of every guide without breaking the prose apart.
    """
    names = ARTICLE_DIAGRAMS.get(slug, [])
    figs = [diagram_html(n, code, rel) for n in names]

    if code == 'en' and photo_paths:
        figs.append(photo_html(photo_paths, None, slug, code, rel))

    if not figs:
        return body_html

    parts = re.split(r'(?=<h[23][\s>])', body_html)
    if len(parts) < 2:
        return body_html + ''.join(figs)

    out = [parts[0]]
    queue = list(figs)
    for part in parts[1:]:
        if queue:
            out.append(queue.pop(0))
        out.append(part)
    out.extend(queue)
    return ''.join(out)
